// Compiles every schema to JavaScript ahead of time.
//
// Ajv normally turns a schema into a validator with `new Function`, at run
// time. A page served under `script-src 'self'` cannot do that: the browser
// refuses, the module throws while loading, and the whole application goes
// blank. Neither the tests nor `vite dev` catch it — Node has no CSP, and the
// dev server never applies site/public/_headers.
//
// So the validators are generated here instead, as plain modules that only run
// code the CSP already allows. The output goes to generated/, one level under
// the package, so `../generated/validators.js` resolves the same from src/ and
// from dist/.
//
//   node scripts/build-validators.mjs        (runs after tsc; see `npm run build`)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import AjvModule from "ajv/dist/2020.js";
import standaloneModule from "ajv/dist/standalone/index.js";
import addFormatsModule from "ajv-formats";
import { _ } from "ajv";
import { schemas, reportProfile } from "../dist/schema.generated.js";

const Ajv = AjvModule.default ?? AjvModule;
const standaloneCode = standaloneModule.default ?? standaloneModule;
const addFormats = addFormatsModule.default ?? addFormatsModule;

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "generated");

/** The identifier each schema is exported under. Mirrored in validators.d.ts. */
const exportNameFor = (version) => `v${version.replace(/\./g, "_")}`;

const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: {
    source: true,
    esm: true,
    // Emitted verbatim; the matching import is prepended below.
    formats: _`fullFormats`,
  },
});
addFormats(ajv);

const exports = {};
for (const [version, schema] of Object.entries(schemas)) {
  ajv.addSchema(schema, version);
  exports[exportNameFor(version)] = version;
}
ajv.addSchema(reportProfile, "report");
exports["report"] = "report";

let code = standaloneCode(ajv, exports);

// Ajv still reaches for its runtime helpers with `require`, even asked for ESM.
// Hoist each one into a real import so the file is valid ESM and a bundler can
// see the dependency.
//
// The helpers are CommonJS, and `require("x").default` is not the same thing as
// `import x from "x"`: Node hands the whole `module.exports` to a default
// import, so the binding would be the wrapper rather than the function. Vite
// happens to interop differently, which is worse — it would work in the browser
// and fail in Node. Unwrapped explicitly below, the way this package already
// treats Ajv itself.
const runtimeImports = new Map();
code = code.replace(
  /require\("(ajv\/dist\/runtime\/[\w/-]+)"\)\.default/g,
  (_match, specifier) => {
    const alias = `rt_${specifier.split("/").pop().replace(/-/g, "_")}`;
    runtimeImports.set(alias, `${specifier}.js`);
    return alias;
  },
);

// The whole point of this file. If any of these slips through, the page goes
// blank again on a host that sets the CSP, and nothing local would notice.
//
// Checked before the header goes on, because the header talks about the very
// constructs it is looking for.
for (const forbidden of [/new Function/, /\brequire\(/, /\beval\(/]) {
  if (forbidden.test(code)) {
    throw new Error(`generated validators still contain ${forbidden} — cannot ship this`);
  }
}

const header = [
  "// Generated by scripts/build-validators.mjs. Do not edit.",
  "// Compiled ahead of time so that validating a document needs no code built",
  "// from a string at run time, which a strict Content-Security-Policy forbids.",
  'import { fullFormats } from "ajv-formats/dist/formats.js";',
  ...[...runtimeImports].map(([alias, specifier]) => `import mod_${alias} from "${specifier}";`),
  ...[...runtimeImports].map(
    ([alias]) => `const ${alias} = mod_${alias}.default ?? mod_${alias};`,
  ),
  "",
].join("\n");

// `"use strict"` is implicit in a module and illegal to keep before imports.
code = header + code.replace(/^"use strict";/, "");

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "validators.js"), code);

const names = Object.keys(exports).join(", ");
console.log(`validators.js written: ${names} (${(code.length / 1024).toFixed(0)} kB, no eval)`);
